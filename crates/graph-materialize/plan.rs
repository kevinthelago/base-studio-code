// THE PURE PLANNING CORE of `crates/graph-materialize/build.rs` — path → module path, path → record
// id, and units → the generated `crate.rs`.
//
// NOTE these are `//` comments and not `//!` module docs on purpose: this file is `include!`d, and an
// inner doc comment does not survive that (E0753, "expected outer doc comment") — the same rule that
// keeps every migrated crate's `lib.rs` a real file.
//
// # Why this is a second file next to a build script
//
// `crates/graph-materialize` was not a package — a bare `build.rs` that 54 crates point their
// `build =` key at — so it had no test target and nothing here could ever be asserted. Every rule
// below — which file is which module, which id says "this record IS that file", and the line-offset
// arithmetic that makes a compiler error inside a 12,609-line record navigable — was observable only
// by compiling a crate and reading the output.
//
// IT IS A PACKAGE NOW (`graph-materialize-becomes-a-real-build-dependency`), so `src/tests.rs` asserts
// these rules directly. The file split survives that for a different reason: `build.rs` — what the 54
// existing adopters compile — and `src/lib.rs` — what a crate at another depth takes as a
// build-dependency and calls — `include!` THIS FILE and `emit.rs` beside it, so both entry points run
// one implementation rather than a copy that can drift.
//
// # The nesting scheme (`graph-materialize-takes-nested-modules-and-mod-rs`)
//
// A directory under `src/` becomes a NESTED `mod` block, mirroring the directory tree, because the
// module path is part of the program: `crate::cli::nouns::render` resolves through it, and every
// `use super::…` inside a nested module depends on it. Flattening `cli/nouns.rs` to a `cli_nouns`
// record would have been a much smaller change here and a rewrite of ~17,900 lines of the four blocked
// crates, since every intra-crate path would have had to move with it.
//
// A directory module's own body comes from whichever of the two shapes Rust allows, and BOTH map onto
// the DIRECTORY name:
//
// ```text
// crates/plandb/src/cli.rs          ->  mod cli          (2018 style: the body sits beside the dir)
// crates/plandb/src/cli/nouns.rs    ->  mod cli::nouns
// crates/bsc-news/src/signals/mod.rs->  mod signals      (mod.rs style)
// crates/bsc-news/src/signals/framing.rs -> mod signals::framing
// ```
//
// `mod.rs` maps to its DIRECTORY, never to a module literally called `mod` — which is what the
// basename-derived name emitted before this change and would not have compiled.
//
// # The id is derived from the PATH, and must agree with `extract::module_id`
//
// Selection is `id == expected_id(crate_dir, rest)`, which is the statement "this record is that whole
// file" — the discriminator that keeps a function record lifted out of `install.rs` from being mistaken
// for `install.rs` itself. It has to equal `bsc_graph::extract::module_id`, which `bsc graph emit` uses
// for exactly the same judgement, and `migrate-crate` uses to name what it writes. Note `mod.rs` keeps
// its `mod` SEGMENT in the id (`bsc-news--signals--mod.rs`): the id names the FILE, the module name
// names the module, and collapsing the two would make `signals/mod.rs` and a hypothetical
// `signals.rs` indistinguishable in the store.
//
// `crates/bsc-graph/src/migrate.rs::expected_id_agrees_with_extract_module_id` pins the agreement over
// every real path in this tree.

/// The generated file's preamble, and the FIRST thing `render` writes.
///
/// It is a constant here rather than a literal in `build.rs` because every module's offset is a line
/// number measured past it: a preamble that changed height in one place and not the other would move
/// every reported line while both halves still looked correct.
pub const PREAMBLE: &str = "\
// GENERATED by crates/graph-materialize/build.rs from graph/algorithms.json — do not edit;\n\
// the edit would be lost on the next build. Edit the RECORD, then promote it:\n\
//     bsc graph impl get <id>\n\
//     bsc graph impl set --id <id> --code-file <f>\n\
//     bsc graph promote --id <id>\n\
// A compiler error below points at THIS file; each module header gives the line offset back\n\
// to its record.\n\n";

/// One record selected for materialization, with its module path already resolved from its `src`.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Unit {
    /// The record id, reproduced verbatim into the module's offset header.
    pub id: String,
    /// The module path from the crate root — `["cli", "nouns"]`.
    pub path: Vec<String>,
    /// The record's source, emitted VERBATIM and at column 0 so its line numbers stay arithmetic.
    pub code: String,
    /// `"pub "`, `""` or e.g. `"pub(crate) "` — including the trailing space when non-empty.
    pub vis: String,
    /// Outer attributes, emitted above the declaration in the order the author wrote them.
    pub attrs: Vec<String>,
}

/// The crate ROOT's record, split into the two halves the shared root wants.
///
/// One record, two destinations: the `//!` prose becomes `$OUT_DIR/crate_doc.md`, which the shared
/// root picks up with `#![doc = include_str!(…)]`, and everything else becomes the TOP of
/// `$OUT_DIR/crate.rs`, which it `include!`s. That is the whole capability
/// `the-crate-body-is-a-record-not-only-its-children` adds: before it, the root record could carry
/// documentation and nothing else, so a crate whose implementation IS its root — five of them, with no
/// child module for `migrate-crate` to see — could not be migrated at all.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct RootUnit {
    /// The record id, reproduced into the generated file's offset header.
    pub id: String,
    /// The crate's own documentation, as MARKDOWN — no `//!` markers.
    pub doc: String,
    /// The crate root's program, ready to `include!`, or `None` for a `role: doc` record that holds
    /// prose and nothing else.
    pub body: Option<String>,
}

/// Split a crate root's Rust source into its crate-level documentation and an `include!`-able body.
///
/// # The `//!` lines are REWRITTEN, never removed, and that is the whole trick
///
/// An inner doc comment cannot survive `include!` (E0753), so the leading `//!` block has to stop being
/// one. Deleting it would work and would silently break the ONE thing that makes a 500-line record
/// navigable: every module header says "line N here is line N-<offset> in the record", and dropping k
/// lines off the front makes that subtraction wrong by k for every line below it. So each `//!` becomes
/// `//` — same line, same count, same arithmetic, and a reader of the generated file still sees the
/// prose that a rustdoc reader gets from `crate_doc.md`.
///
/// # Only the LEADING run
///
/// The split point is the first line that is neither blank nor a `//!` comment. `//!` deeper in the
/// file belongs to an inline `mod x { //! … }`, which is legal inside an included file and must be
/// left exactly as written. A root that opens with a plain `//` comment therefore contributes no crate
/// documentation — correct, because that comment is not documentation either.
pub fn split_root(code: &str) -> (String, String) {
    let mut doc: Vec<String> = Vec::new();
    let mut body: Vec<String> = Vec::new();
    let mut in_head = true;
    for line in code.lines() {
        if in_head {
            let trimmed = line.trim_start();
            if let Some(rest) = trimmed.strip_prefix("//!") {
                doc.push(rest.strip_prefix(' ').unwrap_or(rest).to_string());
                body.push(line.replacen("//!", "//", 1));
                continue;
            }
            if trimmed.is_empty() {
                body.push(line.to_string());
                continue;
            }
            in_head = false;
        }
        body.push(line.to_string());
    }
    while doc.last().is_some_and(|l| l.trim().is_empty()) {
        doc.pop();
    }
    (terminated(doc.join("\n")), terminated(body.join("\n")))
}

/// `s` with a trailing newline, unless it is empty. An empty doc must stay EMPTY — the shared root
/// includes `crate_doc.md` unconditionally, and a lone newline would render as a blank first line on
/// every crate that has authored no prose.
fn terminated(mut s: String) -> String {
    if !s.is_empty() && !s.ends_with('\n') {
        s.push('\n');
    }
    s
}

/// The module PATH denoted by a source path relative to `crates/<crate>/src/`, or `None` when the file
/// is not a module of this crate.
///
/// `None` for the crate ROOT (`lib.rs` / `main.rs`), which is not a MODULE of the crate: `main.rs`
/// counts because a binary crate declares its modules there and `include!`s the generated file there,
/// so materializing it would make the root try to include itself. `None` too for a stray `src/mod.rs`,
/// which denotes no module at all.
///
/// # The root is NOT permanent floor, and this comment used to say it was
///
/// It read "stays a real file because `include!` refuses crate-level `//!` docs and `#![…]` inner
/// attributes". BOTH HALVES WERE ANSWERABLE (`a-crate-root-is-shared-so-a-crate-is-one-file`). The
/// E0753 refusal is about an INCLUDED file; `#![doc = include_str!(concat!(env!("OUT_DIR"),
/// "/crate_doc.md"))]` in the REAL root is legal, and `include_str!` resolves out of `OUT_DIR`, which
/// this build script writes — so the root can be ONE shared file
/// (`crates/graph-materialize/crate_root.rs`) that every adopter's `[lib] path` points at, and each
/// crate still gets its own rustdoc. The four inner attributes in this repo moved to their manifests'
/// `[lints]` tables, stable since Rust 1.74.
///
/// So the ROOT is a record too, selected by [`Plan::select_doc`] rather than here — this `None` is now
/// the statement "not a module", which is what makes the two selections unable to collide.
pub fn module_path(rest: &str) -> Option<Vec<String>> {
    let stem = rest.strip_suffix(".rs")?;
    if stem == "lib" || stem == "main" {
        return None;
    }
    let mut segments: Vec<String> = stem.split('/').filter(|s| !s.is_empty()).map(str::to_string).collect();
    // `<dir>/mod.rs` IS the directory module. Dropping the final `mod` segment is the whole fix for the
    // shape that emitted `pub mod mod { … }`.
    if segments.last().map(String::as_str) == Some("mod") {
        segments.pop();
    }
    if segments.is_empty() {
        return None;
    }
    Some(segments)
}

/// The record id that says "this record IS that whole file", for a path relative to
/// `crates/<crate>/src/`.
///
/// Mirrors `bsc_graph::extract::module_id`: drop the structural `crates/` and `src/` segments, kebab
/// each remaining segment, join with `--`. Rust module names are snake_case and crate directory names
/// are already kebab, so kebabing is exactly a `_` → `-` swap here — the fuller `kebab` in `extract`
/// also splits camelCase humps, which no Rust path segment has.
///
/// Each segment is kebabed and THEN joined, never the other way round: kebabing the joined string would
/// collapse the `--` boundary to a single `-`, and `plandb--cli--nouns` would become
/// `plandb-cli-nouns`, colliding with a crate legitimately named that.
pub fn expected_id(crate_dir: &str, rest: &str) -> String {
    let stem = rest.strip_suffix(".rs").unwrap_or(rest);
    let mut segments: Vec<String> = vec![crate_dir.replace('_', "-")];
    segments.extend(stem.split('/').filter(|s| !s.is_empty()).map(|s| s.replace('_', "-")));
    format!("{}.rs", segments.join("--"))
}

/// The generated `crate.rs` body, or a hard error naming what is wrong with the selection.
///
/// # Failure is loud, in three shapes
///
/// * two records claiming ONE module path — it happened when a rename left the superseded id in the
///   store with the same `src`, and the emitted `pub mod cli` twice reached the compiler as E0428;
/// * a nested module whose PARENT has no record — the child cannot be placed, and synthesizing an empty
///   parent would invent a visibility the crate never declared;
/// * nothing selected at all, which the caller reports because it knows the prefix it searched.
///
/// `header` is the generated file's preamble and is emitted FIRST, because the offsets below are line
/// numbers in the finished file. `src_prefix` is the crate's repo-relative source root
/// (`crates/plandb/src/`, `src-tauri/src/`) and appears ONLY in the missing-parent error, which has to
/// name a real file — it was hard-coded as `crates/<crate>/src/` until a crate could sit at another
/// depth (`graph-materialize-becomes-a-real-build-dependency`).
///
/// # The offset header, at every depth
///
/// Each module opens with `// record <id> — line N here is line N-<offset> in the record.`, where
/// `offset` is that header's own line number in this file. So record line 1 lands at generated line
/// `offset + 1` and the subtraction is exact — which is the ONLY thing making a compiler error inside a
/// 12,609-line record navigable. Bodies are emitted at COLUMN 0, never indented to their nesting depth,
/// because indenting would change the columns a compiler error points at and buy nothing.
pub fn render(
    mut units: Vec<Unit>,
    root: Option<(&str, &str)>,
    crate_dir: &str,
    src_prefix: &str,
    header: &str,
) -> Result<String, String> {
    units.sort_by(|a, b| a.path.cmp(&b.path));
    if let Some(dup) = units.windows(2).find(|w| w[0].path == w[1].path) {
        return Err(format!(
            "two records claim module `{}` of crate `{crate_dir}`: `{}` and `{}`. One is superseded — \
             remove it from the store (`bsc graph impl remove <id>`) and re-promote.",
            dup[0].path.join("::"),
            dup[0].id,
            dup[1].id
        ));
    }
    // A parent must exist before any child can be placed inside it. Checked over the SORTED paths, so a
    // prefix always precedes what it contains.
    let paths: Vec<&[String]> = units.iter().map(|u| u.path.as_slice()).collect();
    for p in &paths {
        if p.len() > 1 {
            let parent = &p[..p.len() - 1];
            if !paths.contains(&parent) {
                return Err(format!(
                    "module `{}` of crate `{crate_dir}` has no record for its parent `{}` — a nested \
                     module cannot be placed without one. Harvest the directory module itself \
                     (`{src_prefix}{}.rs` or `{src_prefix}{}/mod.rs`) and promote it.",
                    p.join("::"),
                    parent.join("::"),
                    parent.join("/"),
                    parent.join("/"),
                ));
            }
        }
    }

    // The generated file's own preamble is part of `out` BEFORE the first module is emitted, because
    // the offsets are line numbers in THIS FILE. Rendering the modules and prepending the preamble
    // afterwards would shift every one of them by the preamble's height, silently — the arithmetic
    // would still look right and every reported line would be wrong.
    let mut out = String::from(header);
    // THE CRATE ROOT'S OWN BODY GOES FIRST, at the top level, because that is where it was. Item order
    // is nothing to rustc, but it is everything to a reader diffing the generated file against the root
    // it replaced. Its offset header is computed exactly as a module's is — see `emit_level`.
    if let Some((id, body)) = root {
        let body_starts_at = out.lines().count() + 1;
        out.push_str(&format!("// record `{id}` — line N here is line N-{body_starts_at} in the record.\n"));
        out.push_str(body);
        if !body.ends_with('\n') {
            out.push('\n');
        }
    }
    emit_level(&mut out, &units, 0, &[]);
    Ok(out)
}

/// Emit every unit whose path is `prefix + [one more segment]`, recursing into each.
///
/// `units` is sorted by path, so a parent immediately precedes its subtree; the recursion still scans
/// the whole slice rather than tracking ranges, because a crate has tens of modules and the clarity is
/// worth more than the asymptotics.
fn emit_level(out: &mut String, units: &[Unit], depth: usize, prefix: &[String]) {
    for u in units.iter().filter(|u| u.path.len() == depth + 1 && u.path.starts_with(prefix)) {
        for a in &u.attrs {
            // SKIP an outer attribute the module body already states as an inner one. `crates/data`
            // gated `meta` twice — `#[cfg(feature = "duckdb-store")]` on the declaration and
            // `#![cfg(feature = "duckdb-store")]` at the top of the body. Legal in two files;
            // materialization puts both on ONE item, which rustc rejects with "item has both inner and
            // outer attributes". The body's copy is inside the record and must not be rewritten, so the
            // redundant outer one gives way.
            let inner = a.trim().replacen("#[", "#![", 1);
            if u.code.contains(&inner) {
                continue;
            }
            out.push_str(a);
            out.push('\n');
        }
        out.push_str(&format!("{}mod {} {{\n", u.vis, u.path[depth]));
        let body_starts_at = out.lines().count() + 1; // the body begins after the header line below
        out.push_str(&format!("    // record `{}` — line N here is line N-{body_starts_at} in the record.\n", u.id));
        out.push_str(&format!("{}\n", u.code));
        // Children go INSIDE, after the parent's own body. Their `mod <child>;` declarations are not in
        // the parent record — `migrate-crate` strips them, because materialization is what declares
        // them now and a leftover one would look for a file that no longer exists.
        emit_level(out, units, depth + 1, &u.path);
        out.push_str("}\n");
    }
}

// ── INTEGRATION TEST TARGETS (`a-rust-record-test-runs-and-an-edge-reaches-the-seed`) ──────────────
//
// Everything above materializes a crate's `src/` — its MODULES. An integration test is not a module:
// `crates/<c>/tests/<name>.rs` is its own crate root, compiled against the public API from OUTSIDE the
// library, which is the whole reason it is in `tests/` rather than in a `#[cfg(test)] mod`.
//
// That distinction is why a carried Rust test could not simply be re-homed as a `role: test` module
// record — the path every `role: test` record already runs by. Doing that would silently grant it
// private access, which changes what the test PROVES rather than where it lives.
//
// So a test target is materialized on its own terms, from the EDGE tier: an edge already carries the
// whole test source in `tests[]` and the member records it spans in `members`, which is exactly a
// relationship over several modules. The output goes to `$OUT_DIR/tests/<name>.rs` and is reached by
// `crates/graph-materialize/test_root.rs` — ONE shared file, byte-identical for every adopter, because
// `CARGO_CRATE_NAME` is the TARGET's name and resolves the body per target.

/// One integration-test target selected for materialization, from the edge that carries it.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct TestTarget {
    /// The edge id, reproduced into the generated file's header.
    pub id: String,
    /// The cargo target name — the file stem, and what `CARGO_CRATE_NAME` expands to in the shared
    /// root, so it is also the `$OUT_DIR/tests/<name>.rs` basename.
    pub name: String,
    /// The test's source, emitted VERBATIM and at column 0 so its line numbers stay arithmetic.
    pub code: String,
}

/// The cargo TEST-TARGET name denoted by a path relative to `crates/<crate>/tests/`, or `None` when
/// the path denotes no target.
///
/// Cargo auto-discovers exactly `tests/*.rs` as targets; anything deeper is a MODULE of one of them
/// and has no target name of its own, so a nested path yields `None` rather than a target that would
/// be declared and never compiled. `mod.rs` likewise denotes no target.
pub fn test_target_name(rest: &str) -> Option<String> {
    let stem = rest.strip_suffix(".rs")?;
    if stem.is_empty() || stem.contains('/') || stem == "mod" {
        return None;
    }
    Some(stem.to_string())
}

/// The generated `$OUT_DIR/tests/<name>.rs` body for one target.
///
/// The header is the same shape a module's is and for the same reason: a compiler error inside the
/// generated file must be navigable back into the record. The body starts on the line AFTER the
/// header, so record line 1 is generated line 2 and the subtraction is exact.
pub fn render_test_target(t: &TestTarget) -> String {
    // THE LEADING `//!` RUN IS REWRITTEN, by the rewriter that already exists. This file is
    // `include!`d by the shared test root, and an inner doc comment does not survive `include!`
    // (E0753) - the same refusal that shaped `split_root` for crate roots. Every real integration
    // test in this repo opens with a `//!` block, so it is the common case rather than a corner:
    // `wire_contract.rs` failed to compile on exactly it. `split_root` is reused verbatim rather than
    // restated, because it already rewrites `//!` to `//` IN PLACE - same line, same count, same
    // arithmetic - which is precisely what the offset header below depends on. Its documentation half
    // is discarded: nothing renders a test target's rustdoc.
    let (_doc, body) = split_root(&t.code);
    let mut out = String::from(TEST_PREAMBLE);
    let body_starts_at = out.lines().count() + 1;
    out.push_str(&format!("// edge `{}` \u{2014} line N here is line N-{body_starts_at} in the record.\n", t.id));
    out.push_str(&body);
    if !body.ends_with('\n') {
        out.push('\n');
    }
    out
}

/// The preamble of a generated test target — a constant for the same reason [`PREAMBLE`] is: a
/// preamble that changed height in one place and not the other would move every reported line while
/// both halves still looked correct.
pub const TEST_PREAMBLE: &str = "\
// GENERATED by crates/graph-materialize from graph/algorithms.json — do not edit; the edit would be\n\
// lost on the next build. Edit the EDGE, then promote it:\n\
//     bsc graph edge get <id>\n\
//     bsc graph edge set --id <id> --members <a,b> --src <path>\n\
//     bsc graph promote --id <id>\n\n";
