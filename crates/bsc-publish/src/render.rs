//! Issue-body rendering — a CROSS-LANGUAGE WIRE CONTRACT, not a formatting preference.
//!
//! The published body carries a hidden `<!-- bsc:ref=... -->` marker, and the GitHub -> plan.db
//! recovery path parses it back out to reconstruct a planner-local `ref` (and therefore the
//! `dependsOn` links, which reference refs rather than GitHub numbers). GitHub persists no such
//! field natively, so that marker is the single enabler for lossless recovery.
//!
//! That makes this a byte-exact contract with the TypeScript `renderIssueBody` / `refMarker` /
//! `parseRefMarker` in `@/features/planner/issues/planIssues`. If the two drift, issues published
//! by one and recovered by the other silently lose their refs — a failure that shows up as
//! dependency links quietly disappearing, not as an error. `body_fixtures.json` is shared with the
//! TS tests for exactly that reason, the same way the tunnel protocol fixtures are.

use plandb::PlanIssue;

/// The hidden HTML-comment marker carrying an issue's planner-local `ref` through a publish.
/// Invisible in GitHub's rendered view, present in the raw body.
pub fn ref_marker(r#ref: &str) -> String {
    format!("<!-- bsc:ref={} -->", r#ref)
}

/// Extract the planner-local ref from a published issue body's marker, or `None`.
///
/// Mirrors the TS regex `/<!--\s*bsc:ref=([^\s>]+)\s*-->/` — tolerant of the whitespace variations
/// a hand-edited body might pick up, and stopping at whitespace or `>` so a marker glued to
/// following text still yields the bare ref.
pub fn parse_ref_marker(body: &str) -> Option<String> {
    let start = body.find("<!--")?;
    let rest = &body[start + 4..];
    let end = rest.find("-->")?;
    let inner = rest[..end].trim();
    let value = inner.strip_prefix("bsc:ref=")?;
    let value: String = value.chars().take_while(|c| !c.is_whitespace() && *c != '>').collect();
    if value.is_empty() {
        None
    } else {
        Some(value)
    }
}

/// The full GitHub issue body for a plan row: the prose, then acceptance criteria as an unchecked
/// task list, owned globs, dependencies, the provenance footer, and the hidden ref marker.
///
/// Sections are joined by a blank line and EMPTY ONES ARE OMITTED — an issue with no `owns` has no
/// "## Owns" heading at all, rather than a heading over nothing.
pub fn render_issue_body(issue: &PlanIssue) -> String {
    let mut parts: Vec<String> = Vec::new();
    if let Some(body) = issue.body.as_deref() {
        let trimmed = body.trim();
        if !trimmed.is_empty() {
            parts.push(trimmed.to_string());
        }
    }
    if !issue.acceptance.is_empty() {
        let items: Vec<String> = issue.acceptance.iter().map(|a| format!("- [ ] {a}")).collect();
        parts.push(format!("## Acceptance criteria\n{}", items.join("\n")));
    }
    if !issue.owns.is_empty() {
        let items: Vec<String> = issue.owns.iter().map(|o| format!("- `{o}`")).collect();
        parts.push(format!("## Owns\n{}", items.join("\n")));
    }
    if !issue.depends_on.is_empty() {
        let items: Vec<String> = issue.depends_on.iter().map(|d| format!("- {d}")).collect();
        parts.push(format!("## Depends on\n{}", items.join("\n")));
    }
    parts.push("---\n_Auto-generated by the base-studio-code planner._".to_string());
    parts.push(ref_marker(&issue.r#ref));
    parts.join("\n\n")
}

/// The provenance label every app-created issue carries, and its colour.
pub const BSC_ISSUE_LABEL: &str = "bsc-generated";
pub const BSC_ISSUE_LABEL_COLOR: &str = "1f6feb";

/// Append the provenance label unless it is already present (never duplicating it).
pub fn with_provenance_label(labels: &[String]) -> Vec<String> {
    let mut out = labels.to_vec();
    if !out.iter().any(|l| l == BSC_ISSUE_LABEL) {
        out.push(BSC_ISSUE_LABEL.to_string());
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    fn issue(r#ref: &str) -> PlanIssue {
        serde_json::from_value(serde_json::json!({ "ref": r#ref, "title": "T" })).unwrap()
    }

    #[test]
    fn ref_marker_round_trips_and_is_tolerant_of_whitespace() {
        assert_eq!(ref_marker("add-login"), "<!-- bsc:ref=add-login -->");
        assert_eq!(parse_ref_marker("<!-- bsc:ref=add-login -->").as_deref(), Some("add-login"));
        // The TS regex allows arbitrary inner whitespace; a hand-edited body must still recover.
        assert_eq!(parse_ref_marker("<!--bsc:ref=x-->").as_deref(), Some("x"));
        assert_eq!(parse_ref_marker("<!--   bsc:ref=x   -->").as_deref(), Some("x"));
        // Not a marker at all.
        assert_eq!(parse_ref_marker("no marker here"), None);
        assert_eq!(parse_ref_marker("<!-- unrelated comment -->"), None);
    }

    #[test]
    fn a_rendered_body_round_trips_its_own_ref() {
        // The property that matters: whatever render writes, recovery must read back. A drift in
        // either direction breaks dependency links silently.
        let mut i = issue("invite-teammates");
        i.acceptance = vec!["a user can invite".into()];
        let body = render_issue_body(&i);
        assert_eq!(parse_ref_marker(&body).as_deref(), Some("invite-teammates"));
    }

    #[test]
    fn empty_sections_are_omitted_not_left_as_bare_headings() {
        let body = render_issue_body(&issue("r1"));
        assert!(!body.contains("## Acceptance criteria"), "no acceptance ⇒ no heading:\n{body}");
        assert!(!body.contains("## Owns"));
        assert!(!body.contains("## Depends on"));
        // The footer + marker are unconditional.
        assert!(body.contains("_Auto-generated by the base-studio-code planner._"));
        assert!(body.ends_with("<!-- bsc:ref=r1 -->"));
    }

    #[test]
    fn provenance_label_is_appended_once_only() {
        assert_eq!(with_provenance_label(&[]), vec![BSC_ISSUE_LABEL.to_string()]);
        let already = vec![BSC_ISSUE_LABEL.to_string()];
        assert_eq!(with_provenance_label(&already), already, "never duplicated");
        assert_eq!(
            with_provenance_label(&["ui".to_string()]),
            vec!["ui".to_string(), BSC_ISSUE_LABEL.to_string()],
        );
    }
}
