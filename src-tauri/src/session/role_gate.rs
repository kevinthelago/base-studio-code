//! The role gate, derived in Rust (`epic-frontend-logic-over-backend-resources-belongs-in-rust`).
//!
//! ## Why this moved
//!
//! Rust already ENFORCES this policy — `bsc_util::dangerous` and `deny_matches` decide whether a
//! command matches a deny pattern — and already WRITES it: `ensure_session_settings` takes
//! `allowed_commands` / `denied_commands` and puts them in `.claude/settings.json`. What it never did
//! was COMPUTE it. `launch-rules.ts` did, so which commands a `worker` may run was decided in a
//! renderer that this project has watched get SIGKILLed at an 8 GB cap, and Rust recorded an answer it
//! could not check.
//!
//! ## Proved equal before it is trusted
//!
//! A port of security policy that is subtly different is worse than no port, so nothing here is
//! believed on inspection. `roleGate.fixtures.json` is GENERATED from the live TypeScript across every
//! role and both surface/glob shapes, and [`tests`] asserts this module reproduces it case for case.
//! Same contract pattern as `tunnelProtocol.fixtures.json`: one artifact, both languages.
//!
//! This module changes no runtime behaviour yet — the frontend still computes. Flipping the caller is
//! its own item, because that is where the risk is and it deserves its own gate and its own revert.

// NOTHING CALLS THIS YET, AND THAT IS THE POINT OF THIS SLICE. The derivation is proved equal to the
// TypeScript that ships today (see `tests`) BEFORE any caller is switched to it, because flipping the
// caller is where the risk lives and it deserves its own gate and its own revert. Remove this the
// moment `ensure_session_settings` takes a role instead of two computed lists.
#![allow(dead_code)]

use serde::{Deserialize, Serialize};

/// How much of an axis a role gets. Mirrors the TS `AccessTier`.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum Tier {
    None,
    Read,
    Write,
}

/// What a session may do — the input the whole gate derives from.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
// camelCase, because the fixture is generated by the TypeScript and `writeGlobs` silently
// deserializing into nothing is exactly the class of bug this parity test exists to catch — it did,
// on the first run: `documentor` kept its DOC_GLOBS carve-out in TS and lost it here.
#[serde(rename_all = "camelCase")]
pub struct RoleCapability {
    pub role: String,
    pub github: Tier,
    pub git: Tier,
    pub code: Tier,
    pub net: Tier,
    pub ui: Tier,
    #[serde(default)]
    pub write_globs: Vec<String>,
    /// The commands a RESTRICTED role may auto-run. Non-empty is what MAKES a role restricted.
    #[serde(default)]
    pub allow: Vec<String>,
    /// Declared `bsc` surfaces. `None` is NOT the empty list — see [`capability_surfaces`].
    #[serde(default)]
    pub surfaces: Option<Vec<String>>,
}

/// `git` subcommands that WRITE. A `read` tier denies these; a `none` tier denies `git` outright.
const GIT_WRITE_DENY: &[&str] = &[
    "git push", "git commit", "git merge", "git rebase", "git reset", "git revert",
    "git cherry-pick", "git tag", "git am", "git apply",
];

const GH_WRITE_DENY: &[&str] = &[
    "gh issue create", "gh issue edit", "gh issue close", "gh issue reopen",
    "gh issue comment", "gh issue delete", "gh issue lock", "gh issue transfer", "gh issue pin",
    "gh pr create", "gh pr merge", "gh pr close", "gh pr edit", "gh pr comment", "gh pr ready",
    "gh pr review",
    "gh label create", "gh label edit", "gh label delete",
    "gh release create", "gh release edit", "gh release delete",
    "gh repo create", "gh repo edit", "gh repo delete",
    "gh api --method POST", "gh api --method PATCH", "gh api --method PUT", "gh api --method DELETE",
    "gh api -X POST", "gh api -X PATCH", "gh api -X PUT", "gh api -X DELETE",
];

const UI_WRITE_DENY: &[&str] = &[
    "bsc ui set", "bsc ui remove", "bsc ui kit set", "bsc ui kit remove",
    "bsc component set", "bsc component remove", "bsc component kit set", "bsc component kit remove",
];

/// Shell commands that MUTATE FILES. A write-less role is denied these too — the counterpart to its
/// whole-tool Edit/Write deny. Shell redirection (`>`) cannot be prefix-denied; the always-on
/// `bsc-confine` FS hook is the complete layer.
const FILE_WRITE_DENY: &[&str] = &[
    "tee", "dd", "truncate", "install", "cp", "mv", "ln", "patch", "sponge",
    "sed -i", "sed --in-place", "perl -i",
    "vi", "vim", "nano", "emacs", "ed", "ex",
];

const PERSONA_WRITE_DENY: &[&str] = &["bsc persona set", "bsc persona remove", "bsc persona rename"];

/// Interpreters a RESTRICTED role must not reach: its whole surface is one store CLI, and an
/// interpreter is a general-purpose escape from it.
const INTERPRETER_DENY: &[&str] = &["python", "python3", "node", "jq", "perl", "ruby"];

const WRITE_TOOLS: &[&str] = &["Edit", "Write", "NotebookEdit"];

/// Roles whose `code: "none"` may still carry an explicit write boundary (the director's commons
/// pattern). Every OTHER `code: "none"` role writes nothing at all.
/// The DIRECTOR is deliberately absent: its commons carve-out existed only while it was the one
/// non-worker session holding a project hub, and it is `code: "write"` scoped to plan files now.
/// The restricted studio sessions ARE here — their carve-out is a sealed `scratch/**` staging dir
/// inside their own workspace, not project content.
const CARVE_OUT_ROLES: &[&str] =
    &["documentor", "marketer", "designer", "architect", "librarian", "sound-designer"];

pub const TOOLING_REQUEST_COMMAND: &str = "bsc request";

/// A PATH-SCOPED file rule uses ONLY `Edit(<glob>)` — Claude Code matches file-permission rules on
/// the `Edit` tool alone, and that one rule covers every file-editing tool.
pub fn edit_path_rule(glob: &str) -> String {
    format!("Edit({glob})")
}

/// The `settings.json` allow/deny rules for the file-write tools.
#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize)]
pub struct ToolPermissionRules {
    pub allow: Vec<String>,
    pub deny: Vec<String>,
}

/// A role is RESTRICTED when it declares its own auto-run commands: its surface is that list and
/// nothing else.
pub fn is_restricted_role(cap: &RoleCapability) -> bool {
    !cap.allow.is_empty()
}

/// The `bsc` surfaces a role drives, or `None` when it declares none.
///
/// `None` IS NOT THE EMPTY LIST. `None` means UNCONSTRAINED — `bsc` is in the mandatory tier, so a
/// role declaring nothing reaches every surface. An empty list would mean "reaches none", which is
/// the opposite, and conflating them is the mistake this signature exists to prevent.
pub fn capability_surfaces(cap: &RoleCapability) -> Option<Vec<String>> {
    if let Some(s) = cap.surfaces.as_ref().filter(|s| !s.is_empty()) {
        return Some(s.clone());
    }
    let mut out: Vec<String> = Vec::new();
    for entry in &cap.allow {
        let mut parts = entry.split_whitespace();
        if parts.next() != Some("bsc") {
            continue;
        }
        let Some(surface) = parts.next() else { continue };
        if !out.iter().any(|s| s == surface) {
            out.push(surface.to_string());
        }
    }
    (!out.is_empty()).then_some(out)
}

/// May this role file onto the GLOBAL tooling queue? Only the debugger and director, plus any
/// restricted role that explicitly names `bsc request` among its own allowed commands.
pub fn may_file_tooling_request(cap: &RoleCapability) -> bool {
    if cap.role == "debugger" || cap.role == "director" {
        return true;
    }
    cap.allow.iter().any(|c| c.starts_with(TOOLING_REQUEST_COMMAND))
}

/// A `code: "none"` role that still owns an explicit write boundary.
pub fn has_scoped_write_carve_out(cap: &RoleCapability) -> bool {
    CARVE_OUT_ROLES.contains(&cap.role.as_str())
        && cap.code == Tier::None
        && !cap.write_globs.is_empty()
}

/// Whole-tool denies beyond the write tools.
pub fn role_denied_tools(cap: &RoleCapability) -> Vec<String> {
    let mut out = Vec::new();
    // A worker must not spawn its own sub-agents: each reads as fresh activity the coordinator keeps
    // trying to relaunch it for, and it blurs the worker's lane.
    if cap.role == "worker" {
        out.push("Task".to_string());
    }
    // The live prompt-injection surface. `none` turns it off at launch.
    if cap.net == Tier::None {
        out.push("WebFetch".to_string());
        out.push("WebSearch".to_string());
    }
    out
}

/// The file-write tool rules. `db_owned` / `dep_manifests` come from `write-locks.json`, passed in
/// rather than re-read here so the data has ONE loader.
pub fn role_write_rules(
    cap: &RoleCapability,
    db_owned_plan_files: &[String],
    dep_manifest_files: &[String],
) -> ToolPermissionRules {
    if cap.code == Tier::None {
        // Claude Code's precedence is deny > allow, so a whole-tool deny would MASK the narrower
        // per-glob allow. A carve-out therefore emits only the allows; everything outside falls to
        // the default prompt and is hard-blocked by the `bsc-scope` hook.
        if has_scoped_write_carve_out(cap) {
            return ToolPermissionRules {
                allow: cap.write_globs.iter().map(|g| edit_path_rule(g)).collect(),
                deny: Vec::new(),
            };
        }
        return ToolPermissionRules {
            allow: Vec::new(),
            deny: WRITE_TOOLS.iter().map(|t| (*t).to_string()).collect(),
        };
    }
    let allow = cap.write_globs.iter().map(|g| edit_path_rule(g)).collect();
    let deny_files: &[String] = match cap.role.as_str() {
        "planner" | "director" => db_owned_plan_files,
        "worker" => dep_manifest_files,
        _ => &[],
    };
    ToolPermissionRules { allow, deny: deny_files.iter().map(|f| edit_path_rule(f)).collect() }
}

/// The `bsc` surface tiers a session carries.
pub fn session_scopes(cap: &RoleCapability) -> std::collections::BTreeMap<String, Tier> {
    let mut m = std::collections::BTreeMap::new();
    m.insert("ui".to_string(), cap.ui);
    m
}

/// The command denies a session launches with — the security gate itself.
///
/// `active_surfaces` is the ONE catalog (`bsc surface list`), passed in rather than restated.
/// FAIL-OPEN ON AN EMPTY CATALOG, deliberately: the catalog is read from a subprocess, so
/// "unavailable" and "no surfaces exist" are indistinguishable, and complementing against an empty
/// list denies nothing — the safe direction. A declared list NARROWS an already-granted surface; it
/// is not the grant.
pub fn role_denied_commands(cap: &RoleCapability, active_surfaces: &[String]) -> Vec<String> {
    let mut out: Vec<String> = Vec::new();
    let push = |s: &str, out: &mut Vec<String>| {
        if !out.iter().any(|x| x == s) {
            out.push(s.to_string());
        }
    };

    // The command-surface complement: a role that declares surfaces is held to exactly that set.
    if let Some(declared) = capability_surfaces(cap) {
        for surface in active_surfaces {
            if !declared.iter().any(|d| d == surface) {
                push(&format!("bsc {surface}"), &mut out);
            }
        }
    }
    match cap.git {
        Tier::None => push("git", &mut out),
        Tier::Read => for c in GIT_WRITE_DENY { push(c, &mut out) },
        Tier::Write => {}
    }
    match cap.github {
        Tier::None => push("gh", &mut out),
        Tier::Read => for c in GH_WRITE_DENY { push(c, &mut out) },
        Tier::Write => {}
    }
    // FAIL-CLOSED on the tier: only an explicit `write` skips the mutating-verb denies, so a stale
    // capability that predates the `ui` field behaves as `read`, never as an accidental grant.
    if cap.ui == Tier::None {
        push("bsc ui", &mut out);
        push("bsc component", &mut out);
    } else if cap.ui != Tier::Write {
        for c in UI_WRITE_DENY { push(c, &mut out) }
    }
    // A RESTRICTED role keeps the shell-mutation denies even though it HAS a carve-out: its carve-out
    // is a tool-only staging dir, and without this clause the carve-out would silently un-deny them.
    let carve_out_writes_via_shell = has_scoped_write_carve_out(cap) && !is_restricted_role(cap);
    if cap.code == Tier::None && !carve_out_writes_via_shell {
        for c in FILE_WRITE_DENY { push(c, &mut out) }
    }
    if !may_file_tooling_request(cap) {
        push(TOOLING_REQUEST_COMMAND, &mut out);
    }
    // Persona WRITES are the architect's. Reads stay open to everyone — a worker must still be able
    // to see what it is running as.
    if cap.role != "architect" {
        for c in PERSONA_WRITE_DENY { push(c, &mut out) }
    }
    if is_restricted_role(cap) {
        for c in INTERPRETER_DENY { push(c, &mut out) }
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde::Deserialize;

    #[derive(Deserialize)]
    struct Fixture {
        cases: Vec<Case>,
        roles: Vec<String>,
    }
    #[derive(Deserialize)]
    #[serde(rename_all = "camelCase")]
    struct Case {
        role: String,
        surfaces: String,
        globs: String,
        capability: RoleCapability,
        denied_commands: Vec<String>,
        denied_tools: Vec<String>,
        write_rules: ToolPermissionRules,
        scopes: std::collections::BTreeMap<String, Tier>,
    }

    /// The fixture is resolved BY FILENAME under `src/`, the same rule `find_fixture` uses for the
    /// tunnel contract — so moving a feature slice does not break this, but RENAMING the fixture
    /// means updating this call in lockstep.
    fn fixture() -> Fixture {
        let root = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../src");
        let mut found: Vec<std::path::PathBuf> = Vec::new();
        fn walk(dir: &std::path::Path, out: &mut Vec<std::path::PathBuf>) {
            let Ok(rd) = std::fs::read_dir(dir) else { return };
            for e in rd.flatten() {
                let p = e.path();
                if p.is_dir() {
                    walk(&p, out);
                } else if p.file_name().and_then(|n| n.to_str()) == Some("roleGate.fixtures.json") {
                    out.push(p);
                }
            }
        }
        walk(&root, &mut found);
        assert_eq!(found.len(), 1, "expected exactly one roleGate.fixtures.json, got {found:?}");
        serde_json::from_str(&std::fs::read_to_string(&found[0]).unwrap()).unwrap()
    }

    /// `dbOwnedPlanFiles` + `depManifestFiles`, from the one file both languages read.
    fn write_locks() -> (Vec<String>, Vec<String>) {
        let p = std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
            .join("data/permissions/write-locks.json");
        let v: serde_json::Value =
            serde_json::from_str(&std::fs::read_to_string(p).expect("write-locks.json")).unwrap();
        let list = |k: &str| {
            v.get(k)
                .and_then(|x| x.as_array())
                .map(|a| a.iter().filter_map(|s| s.as_str().map(str::to_string)).collect())
                .unwrap_or_default()
        };
        (list("dbOwnedPlanFiles"), list("depManifestFiles"))
    }

    fn surfaces_for(key: &str) -> Vec<String> {
        match key {
            "none" => vec![],
            _ => ["ui", "plan", "graph", "persona", "teams", "request", "fleet", "logs"]
                .iter()
                .map(|s| s.to_string())
                .collect(),
        }
    }

    /// THE POINT OF THIS MODULE: Rust must agree with the TypeScript that ships today, case for
    /// case, before anything is switched over to it. A security policy that is subtly different
    /// after a port is worse than one that was never ported.
    #[test]
    fn rust_derives_the_same_gate_the_typescript_does() {
        let fx = fixture();
        assert!(fx.roles.len() >= 9, "the fixture must cover the real table: {:?}", fx.roles);
        assert!(!fx.cases.is_empty());
        let mut checked = 0;
        for c in &fx.cases {
            let label = format!("{} · surfaces={} · globs={}", c.role, c.surfaces, c.globs);
            let active = surfaces_for(&c.surfaces);

            let mut got = role_denied_commands(&c.capability, &active);
            let mut want = c.denied_commands.clone();
            got.sort();
            want.sort();
            assert_eq!(got, want, "denied commands differ for {label}");

            assert_eq!(role_denied_tools(&c.capability), c.denied_tools, "denied tools differ for {label}");

            // Write rules too — they are the other half of the gate, and they read the SAME
            // `write-locks.json` the TypeScript does, so the comparison is against one source of data
            // rather than two copies of it.
            let locks = write_locks();
            assert_eq!(
                role_write_rules(&c.capability, &locks.0, &locks.1),
                c.write_rules,
                "write rules differ for {label}"
            );
            assert_eq!(session_scopes(&c.capability), c.scopes, "scopes differ for {label}");
            checked += 1;
        }
        assert_eq!(checked, fx.cases.len());
    }

    /// `None` surfaces is UNCONSTRAINED; an empty declared list would be the opposite. The two must
    /// never collapse into each other.
    #[test]
    fn declaring_no_surfaces_is_not_the_same_as_declaring_none() {
        let mut cap = RoleCapability {
            role: "worker".into(), github: Tier::Read, git: Tier::Write, code: Tier::Write,
            net: Tier::Read, ui: Tier::Read, write_globs: vec![], allow: vec![], surfaces: None,
        };
        assert_eq!(capability_surfaces(&cap), None, "no allow, no surfaces ⇒ unconstrained");
        let catalog = surfaces_for("catalog");
        let unconstrained = role_denied_commands(&cap, &catalog);
        assert!(!unconstrained.iter().any(|d| d.starts_with("bsc plan")), "nothing is complemented");

        cap.allow = vec!["bsc ui get".into()];
        assert_eq!(capability_surfaces(&cap), Some(vec!["ui".into()]));
        let narrowed = role_denied_commands(&cap, &catalog);
        assert!(narrowed.iter().any(|d| d == "bsc plan"), "every surface it did NOT name is denied");
        assert!(!narrowed.iter().any(|d| d == "bsc ui"), "and the one it named is not");
    }

    /// FAIL-OPEN on an empty catalog: "unavailable" and "none exist" are indistinguishable here, and
    /// bricking every session on a failed subprocess read is the worse direction.
    #[test]
    fn an_empty_surface_catalog_denies_no_surface() {
        let cap = RoleCapability {
            role: "designer".into(), github: Tier::None, git: Tier::None, code: Tier::None,
            net: Tier::None, ui: Tier::Write, write_globs: vec![], allow: vec!["bsc ui set".into()],
            surfaces: None,
        };
        let denied = role_denied_commands(&cap, &[]);
        assert!(!denied.iter().any(|d| d.starts_with("bsc ") && d.split(' ').count() == 2 && d != "bsc request"),
                "an empty catalog must complement nothing: {denied:?}");
    }
}
